//! TP3 fork (perf/engram-readahead): host-side prediction of the n-gram rows a prefill
//! step will request, so a disk-backed table's reader can read them ahead of the graph.
//!
//! The captured graph stays the authority: it hashes its own tokens and publishes the
//! row ids its lookup consumes, and the reader always serves exactly those ids. A row
//! predicted here only warms the row cache, so a wrong prediction costs disk reads and
//! nothing else. Only the DeepSeek `XOR_MODULO` form over unpartitioned tables is
//! predicted; anything else gets no [`RowHash`] and is never read ahead.
//!
//! The derivation follows b12x's CPU oracle (`sequence/engram/reference.py`, the
//! DeepSeek V4.1 `engram.py` equation): compressed tokens through the declared token
//! map, positions before the prompt read as the mapped pad token, and a dead position
//! (excluded, or outside the map) pads its own lag and every older one.

use std::sync::Arc;

/// Declared hash geometry of one unpartitioned `XOR_MODULO` table.
#[derive(Clone, Debug, PartialEq, Eq)]
pub(crate) struct RowHash {
    /// N-gram order per head (2, 3 or 4).
    pub orders: Vec<u32>,
    /// One multiplier per lag (`max(orders)` of them).
    pub multipliers: Vec<u64>,
    pub primes: Vec<u64>,
    pub offsets: Vec<u64>,
    /// Rows stored in the table file.
    pub rows: u64,
    pub token_map: Arc<[u32]>,
    pub pad_token_id: u32,
}

impl RowHash {
    /// Tokens of history one query position needs besides itself.
    pub(crate) fn history(&self) -> usize {
        self.orders.iter().copied().max().unwrap_or(2).max(2) as usize - 1
    }

    pub(super) fn heads(&self) -> usize {
        self.primes.len()
    }

    fn valid(&self) -> bool {
        let heads = self.heads();
        heads != 0
            && self.orders.len() == heads
            && self.offsets.len() == heads
            && self.multipliers.len() > self.history()
    }

    /// The compressed id of the token at `position`, or -1 when it never enters an
    /// n-gram (excluded, such as an image position, or outside the token map).
    fn compressed(&self, tokens: &[u32], position: usize, excluded: &impl Fn(usize) -> bool) -> i64 {
        if excluded(position) {
            return -1;
        }
        self.token_map
            .get(tokens[position] as usize)
            .map_or(-1, |&value| value as i64)
    }

    /// Append the rows query positions `[first, end)` of `tokens` request, `heads` per
    /// position in head order, skipping rows outside the table. History before `first`
    /// comes from `tokens`; positions before 0 read as the mapped pad token, which is the
    /// history a fresh request is seeded with. `window` is caller-owned scratch.
    pub(crate) fn predict(
        &self,
        tokens: &[u32],
        first: usize,
        end: usize,
        excluded: impl Fn(usize) -> bool,
        window: &mut Vec<i64>,
        out: &mut Vec<i64>,
    ) {
        let end = end.min(tokens.len());
        if first >= end || !self.valid() {
            return;
        }
        let Some(&pad) = self.token_map.get(self.pad_token_id as usize) else {
            return;
        };
        let pad = pad as i64;
        let history = self.history();
        // window[i] holds position first - history + i; positions before 0 are pad.
        window.clear();
        window.extend((0..history).map(|lag| {
            (first + lag).checked_sub(history).map_or(pad, |position| self.compressed(tokens, position, &excluded))
        }));
        window.extend((first..end).map(|position| self.compressed(tokens, position, &excluded)));
        for current in history..window.len() {
            for head in 0..self.heads() {
                let order = self.orders[head] as usize;
                let mut rolling = 0i64;
                let mut blocked = false;
                for lag in 0..order.min(history + 1) {
                    let value = window[current - lag];
                    blocked |= value < 0;
                    rolling ^= (if blocked { pad } else { value }).wrapping_mul(self.multipliers[lag] as i64);
                }
                let prime = self.primes[head] as i64;
                if prime < 2 {
                    continue;
                }
                let Some(row) = rolling.rem_euclid(prime).checked_add(self.offsets[head] as i64) else {
                    continue;
                };
                if row >= 0 && (row as u64) < self.rows {
                    out.push(row);
                }
            }
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    // Generated by tp3-tools/engram-readahead/hash_vectors.py from b12x
    // `sequence/engram/reference.py` with the DS41 geometry (`build_geometry()` defaults).
    include!("row_ids_vectors.rs");

    fn table(layer: u32) -> RowHash {
        let (multipliers, primes, offsets, rows) = match layer {
            1 => (MULTIPLIERS_1, PRIMES_1, OFFSETS_1, ROWS_1),
            _ => (MULTIPLIERS_14, PRIMES_14, OFFSETS_14, ROWS_14),
        };
        RowHash {
            orders: (2..=4).flat_map(|order| [order; 8]).collect(),
            multipliers: multipliers.to_vec(),
            primes: primes.to_vec(),
            offsets: offsets.to_vec(),
            rows,
            token_map: TOKEN_MAP.to_vec().into(),
            pad_token_id: 2,
        }
    }

    fn excluded(position: usize) -> bool {
        EXCLUDED.contains(&position)
    }

    #[test]
    fn prompt_rows_match_the_b12x_oracle() {
        for (layer, expected) in [(1, &EXPECTED_1_FRESH), (14, &EXPECTED_14_FRESH)] {
            let hash = table(layer);
            let (mut window, mut out) = (Vec::new(), Vec::new());
            hash.predict(&TOKENS, 0, TOKENS.len(), excluded, &mut window, &mut out);
            let flat: Vec<i64> = expected.iter().flatten().copied().collect();
            assert_eq!(out, flat, "layer {layer}");
        }
    }

    #[test]
    fn any_chunking_reproduces_the_whole_prompt() {
        let hash = table(14);
        let (mut window, mut whole) = (Vec::new(), Vec::new());
        hash.predict(&TOKENS, 0, TOKENS.len(), excluded, &mut window, &mut whole);
        for step in [1, 2, 3, 7, 16, 40] {
            let mut chunked = Vec::new();
            for first in (0..TOKENS.len()).step_by(step) {
                hash.predict(&TOKENS, first, first + step, excluded, &mut window, &mut chunked);
            }
            assert_eq!(chunked, whole, "chunk {step}");
        }
    }

    #[test]
    fn rows_stay_inside_the_table_and_bad_geometry_predicts_nothing() {
        let mut hash = table(1);
        hash.rows = OFFSETS_1[8];
        let (mut window, mut out) = (Vec::new(), Vec::new());
        hash.predict(&TOKENS, 0, 40, excluded, &mut window, &mut out);
        assert!(!out.is_empty() && out.iter().all(|&row| row >= 0 && (row as u64) < OFFSETS_1[8]));
        let mut partial = table(1);
        partial.offsets.pop();
        out.clear();
        partial.predict(&TOKENS, 0, 40, excluded, &mut window, &mut out);
        assert!(out.is_empty());
        // Empty or inverted ranges and a missing pad entry predict nothing.
        let hash = table(1);
        hash.predict(&TOKENS, 10, 10, excluded, &mut window, &mut out);
        hash.predict(&TOKENS, 50, 60, excluded, &mut window, &mut out);
        let mut unmapped = table(1);
        unmapped.pad_token_id = 1000;
        unmapped.predict(&TOKENS, 0, 40, excluded, &mut window, &mut out);
        assert!(out.is_empty());
    }
}
